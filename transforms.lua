-- Vanilla Sprites+ asset transform.
--
-- Runs at install, and again whenever the active game's imported cache
-- changes. It reads the player's own front sprites and writes fixed copies
-- to save/mod-derived/vanilla_sprites_plus/ under the same relative paths,
-- which the engine's asset lookup then uses instead of the originals.
-- No sprite pixels ship with the mod, only the positions below.
--
-- The importer (ImageWriter.matteColor0) only makes white transparent where
-- it can reach it from the image edge. White enclosed by the drawing, like
-- the loop of Articuno's tail, stays opaque and shows up as a white blob on
-- any non-white background. Nothing in the image says which enclosed white
-- is background and which is part of the Pokemon, so the gaps were picked
-- per sprite: Red/Blue by hand, Yellow/Gold/Silver from PokeAPI's
-- transparent sets, and from Crystal Animated Sprites' cleanup where its
-- art matches the game's. Every source was checked pixel for pixel against
-- the game's art first.
--
-- Each name has one entry per game whose art was fixed (the same file name
-- is a different drawing in Red/Blue, Yellow, Gold and Silver):
--   h  fingerprint of the game's sprite (every pixel's shade)
--   e  hand-drawn pixels {y, x, shade}: 1-3 = light grey to black,
--      4 = kept white (white the transparency fill can't pass, used where
--      the Pokemon's own white touched the background with no outline)
--   g  gaps, one {y, x, size} per white area: any pixel in it and its size
--
-- The entry matching the running game's sprite is applied. A sprite with no
-- match, or that fails any check (e.g. a gap of the wrong size), is written
-- back unchanged. mod-derived is shared by every game, so writing back
-- unchanged copies also clears out another game's fixed sprites when you
-- switch games.
