-- djb2 over "WxH:" plus one character per pixel: "." transparent,
-- "0"-"3" white to black, using the engine's own red-channel thresholds.
local function fingerprint(id, w, h)
  local hsh = 5381
  local function add(byte) hsh = (hsh * 33 + byte) % 4294967296 end
  local head = w .. "x" .. h .. ":"
  for i = 1, #head do add(head:byte(i)) end
  for y = 0, h - 1 do
    for x = 0, w - 1 do
      local r, _, _, a = id:getPixel(x, y)
      if a == 0 then add(46)
      elseif r > 0.83 then add(48)
      elseif r > 0.5 then add(49)
      elseif r > 0.17 then add(50)
      else add(51) end
    end
  end
  return string.format("%08x", hsh)
end

local GREY = { [1] = 170 / 255, [2] = 85 / 255, [3] = 0 }

-- Works out every change before touching any pixel, so a sprite that fails
-- a check is left exactly as the game made it.
local function fixPic(id, entries)
  local w, h = id:getDimensions()
  local fp = fingerprint(id, w, h)
  local fix = nil
  for _, e in ipairs(entries) do
    if e.h == fp then fix = e; break end
  end
  if not fix then return false end
  local n = w * h
  -- white = shade 0 as the importer sees it: opaque white or transparent
  local white = {}
  for y = 0, h - 1 do
    for x = 0, w - 1 do
      local r, g, b, a = id:getPixel(x, y)
      white[y * w + x] = (a == 0) or (r == 1 and g == 1 and b == 1)
    end
  end
  local paint = {}
  for _, e in ipairs(fix.e) do
    local i = e[1] * w + e[2]
    if e[3] == 4 or GREY[e[3]] then white[i] = false else return false end
    paint[#paint + 1] = { e[2], e[1], e[3] }
  end
  -- re-run the importer's edge fill with the hand-drawn pixels in place
  local outside, stack = {}, {}
  local function push(i)
    if white[i] and not outside[i] then outside[i] = true; stack[#stack + 1] = i end
  end
  for x = 0, w - 1 do push(x); push((h - 1) * w + x) end
  for y = 0, h - 1 do push(y * w); push(y * w + w - 1) end
  while #stack > 0 do
    local i = stack[#stack]; stack[#stack] = nil
    local x = i % w
    if x > 0 then push(i - 1) end
    if x < w - 1 then push(i + 1) end
    if i >= w then push(i - w) end
    if i < n - w then push(i + w) end
  end
  -- collect each gap's white area and check it's the expected size
  local clear, taken = {}, {}
  for _, g in ipairs(fix.g) do
    local s = g[1] * w + g[2]
    if not white[s] or outside[s] or taken[s] then return false end
    local area, st = { s }, { s }
    taken[s] = true
    while #st > 0 do
      local i = st[#st]; st[#st] = nil
      local x = i % w
      local nb = { x > 0 and i - 1 or -1, x < w - 1 and i + 1 or -1,
                   i >= w and i - w or -1, i < n - w and i + w or -1 }
      for _, j in ipairs(nb) do
        if j >= 0 and white[j] and not outside[j] and not taken[j] then
          taken[j] = true; area[#area + 1] = j; st[#st + 1] = j
        end
      end
    end
    if #area ~= g[3] then return false end
    for _, i in ipairs(area) do clear[#clear + 1] = i end
  end
  -- apply: drawn pixels, white sealed back in by them, then the gaps
  for _, p in ipairs(paint) do
    local v = GREY[p[3]]
    if v then id:setPixel(p[1], p[2], v, v, v, 1) else id:setPixel(p[1], p[2], 1, 1, 1, 1) end
  end
  for i = 0, n - 1 do
    if white[i] and not outside[i] then
      local x = i % w
      local y = (i - x) / w
      local _, _, _, a = id:getPixel(x, y)
      if a == 0 then id:setPixel(x, y, 1, 1, 1, 1) end
    end
  end
  for _, i in ipairs(clear) do
    local x = i % w
    id:setPixel(x, (i - x) / w, 1, 1, 1, 0)
  end
  return true
end

return function(ctx)
  for name, fix in pairs(GAPS) do
    local rel = "battle/front/" .. name .. ".png"
    if ctx.exists(rel) then
      local ok = pcall(function()
        local id = ctx.readImage(rel)
        local okFix = pcall(fixPic, id, fix)
        -- an error part-way through could leave it half-edited, so reload it
        if not okFix then id = ctx.readImage(rel) end
        ctx.writeImage(id, rel)
      end)
      if not ok then
        -- don't leave another game's fixed copy behind
        pcall(function() ctx.writeImage(ctx.readImage(rel), rel) end)
      end
    end
  end
end
